let a = 10;
let b = 5;

const sum = a + b;
const diff = a - b;
const product = a * b;
const quotient = a / b;
const remainder = a % b;

console.log(`Sum of ${a} and ${b} is: ${sum} \n`);
console.log(`Difference of ${a} and ${b} is: ${diff} \n`);
console.log(`Product of ${a} and ${b} is: ${product} \n`);
console.log(`Quotient of ${a} and ${b} is: ${quotient} \n`);
console.log(`Remainder of ${a} and ${b} is: ${remainder} \n`);
