/*
=============================================================================
Problem 5: Assignment Operators

Create a variable with an initial numeric value.

Then use assignment operators to:

- Add a value to it
- Subtract a value from it
- Multiply it by a value
- Divide it by a value

Print the value after each operation.

Use:
+=
-=
*=
/=
=============================================================================
*/

let a = 5;

console.log('On Addition: ', (a += 5)); // a becomes 10
console.log('On Subtraction', (a -= 2)); // a becomes 8
console.log('On Multiplication', (a *= 5)); // a becomes 40
console.log('On Division', (a /= 4)); // a becomes 10
